// Bundle the exact pinned NEAR Connect package for the dependency-free static site.
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';

const here = fileURLToPath(new URL('../', import.meta.url));
await build({
  absWorkingDir: here,
  entryPoints: ['web-src/wallet-entry.mjs'],
  outfile: 'web/wallet.bundle.js',
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: ['es2020'],
  minify: true,
  legalComments: 'inline',
  banner: { js: '/* Bouncer testnet wallet connector; source: web-src/, generated by npm run build:web. */' },
});

/**
 * UNSIGNED, OFFLINE owner-wallet plan for the order-specific Buffer forwarder
 * and exact V12 intent. It never creates a quote/order, contacts NEAR or the
 * seller, opens a wallet, signs, sends, installs a key or authorizes spending.
 * It is not an executor: every stage requires separately authenticated owner
 * approval, fresh same-FINAL checks and durable original-hash reconciliation.
 */
import crypto from 'node:crypto';
import { isDeepStrictEqual } from 'node:util';
import nearApi from 'near-api-js';
import { buildBufferForwarder, BUFFER_FIXED_SKUS } from '../experiments/buffer-forwarder/build.mjs';
import { verifyBufferSpendingReview } from './buffer-wallet-spending-evidence.mjs';
import { BUFFER_WALLET_TRIAL_MAX_ATOMS } from './buffer-wallet-spending-plan.mjs';
import { unsignedSvalinBatchCommitment, assertSvalinBatchMatchesReview } from './svalin-setup-plan.mjs';
import { CIRCLE_TESTNET_USDC as CIRCLE } from '../scripts/circle-testnet-setup.mjs';

const TGAS = 10n ** 12n, NEAR = 10n ** 24n, MAX_REGISTRATION = 10n ** 22n;
// Conservative experimental fixed funding, not a guarantee of storage or gas.
export const BUFFER_FORWARDER_FUNDING_YOCTO = (3n * NEAR).toString();
const validUint = value => typeof value === 'string' && /^(0|[1-9][0-9]{0,38})$/.test(value) && BigInt(value) <= (1n << 128n)-1n;
const sha = value => crypto.createHash('sha256').update(value).digest('hex');
const nearHash = bytes => nearApi.utils.serialize.base_encode(crypto.createHash('sha256').update(bytes).digest());

/**
 * Public terms and a previously retained spending review are required. The
 * quote/order and bearer response must be checked independently; a terms hash
 * is not secret and a returned plan does not prove price, balance or consent.
 * The fixed 3-test-NEAR account funding may leave native storage locked.
 */
export async function buildBufferForwarderWalletPlan({ terms: inputTerms, spendingReview: inputReview,
  trustedSpendingReviewHash, trustedOwnerPublicKey, registrationDepositYocto, nowMs = Date.now() } = {}) {
  const terms = structuredClone(inputTerms), spendingReview = structuredClone(inputReview);
  const identity = verifyBufferSpendingReview({ review: spendingReview, trustedReviewHash: trustedSpendingReviewHash,
    trustedOwnerPublicKey });
  if (!validUint(registrationDepositYocto) || registrationDepositYocto === '0' || BigInt(registrationDepositYocto) > MAX_REGISTRATION ||
      !Number.isSafeInteger(nowMs) || nowMs < 1 || !terms || typeof terms !== 'object' ||
      !validUint(terms.amount) || terms.amount === '0' || BigInt(terms.amount) > BigInt(BUFFER_WALLET_TRIAL_MAX_ATOMS) ||
      BigInt(terms.amount) > BigInt(spendingReview.per_tx_cap_atoms) || BigInt(terms.amount) > BigInt(spendingReview.daily_cap_atoms) ||
      (BUFFER_FIXED_SKUS.includes(terms.sku) ? terms.amount !== '20000000' : terms.sku !== 'custom-brief' || BigInt(terms.amount) < 5_000_000n) ||
      !validUint(terms.native_reserve) || BigInt(terms.native_reserve) < NEAR || BigInt(terms.native_reserve) > 2n * NEAR ||
      !validUint(terms.native_return_cap) || BigInt(terms.native_return_cap) > 2n * NEAR ||
      terms.owner !== identity.owner || terms.vault !== identity.vault || terms.adapter !== identity.adapter ||
      terms.policy_id !== spendingReview.policy_id || terms.vault_agent_public_key !== identity.vault_agent_public_key ||
      terms.forwarder_agent_public_key !== identity.forwarder_agent_public_key) {
    throw new Error('order terms exceed the retained named-testnet spending review or bounded native setup');
  }
  // Includes exact order identifiers, token, payee, price, agent and expiry in
  // the generated bytecode. It does not obtain or validate the private order.
  const artifact = await buildBufferForwarder(terms, { nowMs });
  const t = nearApi.transactions;
  const batches = [
    { id: 'create_buffer_forwarder', signerId: identity.owner, receiverId: identity.adapter, actions: [
      t.createAccount(), t.transfer(BigInt(BUFFER_FORWARDER_FUNDING_YOCTO)), t.deployContract(artifact.wasm),
    ] },
    { id: 'register_buffer_forwarder_circle', signerId: identity.owner, receiverId: CIRCLE, actions: [
      t.functionCall('storage_deposit', { account_id: identity.adapter, registration_only: true }, 50n * TGAS, BigInt(registrationDepositYocto)),
    ] },
    { id: 'pin_buffer_exact_intent', signerId: identity.owner, receiverId: identity.vault, actions: [
      t.functionCall('set_exact_ft_intent', { intent_id: terms.intent_id, policy_id: terms.policy_id, expected_token: CIRCLE,
        payee: identity.adapter, amount: terms.amount, memo: artifact.review.intent_memo, review_hash: artifact.review.review_sha256,
        expires_at_ms: String(terms.expires_at_ms), agent_public_key: identity.vault_agent_public_key }, 100n * TGAS, 1n),
    ] },
  ];
  const stages = [
    { id: batches[0].id, signer_id: identity.owner, receiver_id: identity.adapter,
      prerequisite: 'Verify the direct child is absent and the exact public order, seller terms, bytecode, native funding and owner key at a fresh FINAL block.',
      actions: [{ type: 'create_account' }, { type: 'transfer', deposit_yocto: BUFFER_FORWARDER_FUNDING_YOCTO },
        { type: 'deploy_contract', byte_length: artifact.wasm.length, sha256: artifact.wasm_sha256, near_code_hash: nearHash(artifact.wasm) }] },
    { id: batches[1].id, signer_id: identity.owner, receiver_id: CIRCLE,
      prerequisite: 'Reconcile the original create/deploy receipt; verify keyless forwarder code and owner, Circle code and an absent registration at a fresh FINAL block.',
      actions: [{ type: 'function_call', method: 'storage_deposit', args: { account_id: identity.adapter, registration_only: true },
        gas: String(50n * TGAS), deposit_yocto: registrationDepositYocto }] },
    { id: batches[2].id, signer_id: identity.owner, receiver_id: identity.vault,
      prerequisite: 'Reconcile all earlier originals; verify the exact locked policy, scoped agent keys, token balance, registered code-pinned forwarder, seller terms and unused intent at a fresh FINAL block.',
      actions: [{ type: 'function_call', method: 'set_exact_ft_intent', args: {
        intent_id: terms.intent_id, policy_id: terms.policy_id, expected_token: CIRCLE, payee: identity.adapter, amount: terms.amount,
        memo: artifact.review.intent_memo, review_hash: artifact.review.review_sha256, expires_at_ms: String(terms.expires_at_ms),
        agent_public_key: identity.vault_agent_public_key }, gas: String(100n * TGAS), deposit_yocto: '1' }] },
  ].map((stage, index) => ({ ...stage, action_commitment_sha256: unsignedSvalinBatchCommitment(batches[index]) }));
  for (let i = 0; i < batches.length; i++) assertSvalinBatchMatchesReview(batches[i], stages[i]);
  const review = { format: 'bouncer-buffer-forwarder-wallet-review-v1', status: 'UNSIGNED_OFFLINE_PLAN_ONLY', network: 'testnet',
    owner: identity.owner, vault: identity.vault, adapter: identity.adapter, owner_public_key: trustedOwnerPublicKey,
    spending_review_sha256: trustedSpendingReviewHash, forwarder_review_sha256: artifact.review.review_sha256,
    forwarder_wasm_sha256: artifact.wasm_sha256, forwarder_wasm_near_hash: nearHash(artifact.wasm),
    forwarder_wasm_bytes: artifact.wasm.length, order_terms: terms, native_funding_yocto: BUFFER_FORWARDER_FUNDING_YOCTO,
    registration_deposit_yocto: registrationDepositYocto, stages,
    limitations: [
      'No wallet, transaction, order, quote or provider payment was created by this plan.',
      'The direct child and Circle registration may be unavailable; native storage can remain locked.',
      'Wallet approval, independent durable prompt fencing, fresh stage checks, original-hash recovery and provider verification are required.',
      'Pinning an intent is not payment or delivery; its short expiry and policy limits remain enforced by the vault.',
      'A reviewed brief hash can be guessable and is not encryption; never put a private order or access token in this plan.',
    ], signing_or_broadcast_authorized: false, wallet_approval_obtained: false, independently_fulfilled: false };
  return { review: { ...review, review_sha256: sha(Buffer.from(JSON.stringify(review))) }, batches,
    forwarder_wasm: artifact.wasm, forwarder_review: artifact.review };
}

/** Rebuild an independently retained review from constrained public terms.
 * Neither a matching hash nor this offline verifier proves approval, account
 * state, a durable prompt reservation, or a genuine provider order. */
export async function verifyBufferForwarderWalletReview({ review: rawReview, trustedReviewHash, terms: rawTerms,
  spendingReview: rawSpendingReview, trustedSpendingReviewHash, trustedOwnerPublicKey, nowMs = Date.now() } = {}) {
  const review = structuredClone(rawReview), terms = structuredClone(rawTerms), spendingReview = structuredClone(rawSpendingReview);
  if (!review || typeof trustedReviewHash !== 'string' || !/^[a-f0-9]{64}$/.test(trustedReviewHash) ||
      review.review_sha256 !== trustedReviewHash) throw new Error('independently retained forwarder wallet review required');
  let rebuilt;
  try {
    rebuilt = await buildBufferForwarderWalletPlan({ terms, spendingReview, trustedSpendingReviewHash,
      trustedOwnerPublicKey, registrationDepositYocto: review.stages[1].actions[0].deposit_yocto, nowMs });
    if (!isDeepStrictEqual(review, rebuilt.review)) throw Error('review differs');
  } catch { throw new Error('forwarder wallet review differs from its constrained public terms'); }
  return { review: rebuilt.review, batches: rebuilt.batches };
}
